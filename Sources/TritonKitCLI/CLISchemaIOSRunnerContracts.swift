func iosRunnerOutputContract() -> TKCommandOutputContract {
    TKCommandOutputContract(selector: "host.ios-resident-runner", format: "json", kind: "host-action", model: "IOSRunnerEnvelope", fields: schemaContractFields([
        ("ok", "Bool", true, "Service acceptance; UI submission is not a verified business postcondition"),
        ("result", "Object", false, "Operation-specific doctor/prepare/session/request/receipt result; status probes network health only, never fresh UI automation readiness"),
        ("result.state", "String", false, "Lifecycle state; status network_ready means an authenticated health response, not current UI readiness"),
        ("result.healthVerified", "Bool", false, "status: authenticated network health verified in this call"),
        ("result.automationReady", "Bool|null", false, "status always null: current UI automation readiness is not probed; start true reflects successful startup UI probe"),
        ("result.automationPreviouslyVerified", "Bool", false, "status: historical successful startup UI probe only; never proof that UI automation remains ready now"),
        ("result.artifact", "Object", false, "Screenshot PNG publication metadata; private full-screen image, no target ownership claim"),
        ("result.response.result.artifact", "Object", false, "receipt --output may publish the original cached screenshot PNG; never a fresh UI capture"),
        ("error", "Object", false, "Stable code and sanitized message; unknown outcomes require receipt lookup without automatic retry"),
        ("artifactError", "Object", false, "Screenshot export failure kept separate from the original action envelope; does not change its requestID or erase an accepted action result"),
        ("artifactError.code", "String", false, "Stable screenshot publication failure code; query the original receipt to recover the cached image"),
        ("receiptError", "Object", false, "Private host receipt persistence failure; the original requestID and action outcome remain available for Runner receipt lookup"),
        ("receiptError.code", "String", false, "ios_runner_receipt_save_failed"),
        ("sessionID", "String", false, "Active resident XCTest session identifier"),
        ("requestID", "String", false, "Action correlation/idempotency identifier, scoped to one live session"),
    ]))
}

func iosRunnerSubcommandSchema() -> TKCommandSubcommandSchema {
    let common = ["--session-root", "--timeout", "--format", "--json"]
    let overrides: [TKCommandSchemaOption] = [
        TKCommandSchemaOption(name: "--device", type: "String", required: true, description: "Explicit iOS physical or Simulator selector; no implicit current device"),
        TKCommandSchemaOption(name: "--session-root", type: "Path", description: "Private artifact directory only; target ownership registry and locks remain global and independent of this path"),
        TKCommandSchemaOption(name: "--timeout", type: "Double", description: "Finite durations: prepare max1800, all other operations max120; defaults doctor/status10, prepare600, start120, stop30, request/receipt18. Transport timeout does not cancel a submitted UI action"),
        TKCommandSchemaOption(name: "--team", type: "String", description: "Apple development signing team; omitted requires an unambiguous available team for physical devices"),
        TKCommandSchemaOption(name: "--allow-provisioning-updates", type: "Bool", defaultValue: "false", description: "Opt into Xcode provisioning updates; never automatic"),
        TKCommandSchemaOption(name: "--ttl", type: "Double", defaultValue: "600", description: "Finite 10...3600 seconds; a bounded XCTest session, not permanent background residency"),
        TKCommandSchemaOption(name: "--allow-bundle", type: "[String]", description: "Repeat for each exact target bundle authorized in this session"),
        TKCommandSchemaOption(name: "--bundle-id", type: "String", description: "Exact target bundle from the session allowlist"),
        TKCommandSchemaOption(name: "--identifier", type: "String", description: "Exact element identifier from the latest inspect; exclusive with label"),
        TKCommandSchemaOption(name: "--label", type: "String", description: "Exact element label from the latest inspect; exclusive with identifier"),
        TKCommandSchemaOption(name: "--limit", type: "Int", defaultValue: "40", description: "Returned element budget 1...40; not a bound on internal XCTest AX traversal"),
        TKCommandSchemaOption(name: "--direction", type: "up|down|left|right", description: "Scroll direction"),
        TKCommandSchemaOption(name: "--body-file", type: "Path", description: "Actual Runner route JSON object body, at most 64KiB"),
        TKCommandSchemaOption(name: "--text-file", type: "Path", description: "Nonempty UTF-8 input at most 4096 bytes; private text is not an argv value"),
        TKCommandSchemaOption(name: "--route", type: "String", defaultValue: "/crossApp", description: "Whitelisted Runner route, never an arbitrary URL"),
        TKCommandSchemaOption(name: "--request-id", type: "String", description: "Action idempotency identifier; receipt requires the original action identifier"),
        TKCommandSchemaOption(name: "--output", type: "Path", description: "Fresh private PNG destination; receipt --output recovers a nested cached screenshot without executing a new capture. Screenshots are whole-screen; target ownership needs independent visual verification"),
    ]
    func child(_ name: String, required: [String] = [], optional: [String] = [], selectors: Bool = false) -> TKCommandSubcommandSchema {
        TKCommandSubcommandSchema(name: name, summary: "Bundled iOS Runner \(name)", requiresServer: false, requiresTarget: false,
            sideEffect: ["doctor", "status"].contains(name) ? "readonly" : "automation",
            optionOverrides: overrides.filter { (["--device"] + required + optional + common + (selectors ? ["--identifier", "--label"] : [])).contains($0.name) },
            requiredOptions: ["--device"] + required, oneOfRequiredOptions: selectors ? [["--identifier"], ["--label"]] : [],
            optionalOptions: common + optional, artifacts: ["screenshot", "receipt"].contains(name) ? ["private-png"] : [], retryable: false, nextCommands: ["triton device runner status --device <selector> --json"],
            outputSelectors: ["host.ios-resident-runner"], failureCodes: iosRunnerFailureCodes)
    }
    return TKCommandSubcommandSchema(name: "runner", summary: "Bundled public XCTest Runner lifecycle and cross-App control; no embedded SDK requirement",
        requiresServer: false, requiresTarget: false, optionOverrides: overrides,
        outputSelectors: ["host.ios-resident-runner"], failureCodes: iosRunnerFailureCodes,
        subcommands: [
            child("doctor"), child("prepare", optional: ["--team", "--allow-provisioning-updates"]),
            child("start", optional: ["--ttl", "--allow-bundle"]),
            child("status"), child("stop"), child("request", required: ["--body-file"], optional: ["--route", "--request-id"]),
            child("receipt", required: ["--request-id"], optional: ["--output"]), child("activate", required: ["--bundle-id"], optional: ["--request-id"]),
            child("inspect", required: ["--bundle-id"], optional: ["--limit", "--request-id"]),
            child("tap", required: ["--bundle-id"], optional: ["--request-id"], selectors: true),
            child("scroll", required: ["--bundle-id", "--direction"], optional: ["--request-id"]),
            child("type", required: ["--bundle-id", "--text-file"], optional: ["--request-id"], selectors: true),
            child("screenshot", required: ["--bundle-id", "--output"], optional: ["--request-id"]),
        ])
}
